"""Настройки диктофона стакана.

Отдельный от trading-bot проект: свой каталог, своё окружение, своя служба.
Ключи API здесь не нужны — пишутся только публичные данные, доступа к счёту
у диктофона нет и быть не может.
"""

import os
from pathlib import Path

# --- что пишем -------------------------------------------------------------

# Инструменты MEXC futures. Начинаем с трёх: один эталонный (BTC) и два альта
# из рабочего универса. Больше не берём, пока не измерим реальный объём данных.
# Четыре разных микроструктурных режима, а не четыре случайные монеты:
#   BTC — тонкий шаг (0.013 б.п.) и спред в 11 шагов: цену можно улучшить;
#   ETH — спред заперт на одном шаге, книга глубокая: всегда конец очереди;
#   SOL — спред заперт и шаг грубый (1.05 б.п.): скорее всего непригоден,
#         и это тоже результат, который надо получить, а не предположить;
#   XAU — золото: единственный не-крипто инструмент, по выходным поток
#         падает в 4-5 раз — бесплатная проверка, зависит ли эдж от его
#         плотности. Но ходит меньше всех (ход/спред = 3), поэтому событий
#         даёт вдвое меньше остальных и первый на вылет, если понадобится
#         место;
#   HYPE — ход/спред 60 при 23k у касания. Спред скачет (0.12-1.46), но
#         медиана держится у 0.12;
#   XRP — ход/спред 16, зато книга втрое глубже ETH и спред вообще не
#         шевелится (0.65-0.65 за всю серию замеров). Порог «ход/спред 20»
#         я взял с потолка, и XRP под него не проходит формально — но при
#         такой глубине и стабильности он полезнее половины списка.
#
# Отбор считается командой ./universe. Решает не спред сам по себе, а ход
# цены ОТНОСИТЕЛЬНО спреда И глубина у касания: ZEC и PEPE ходят лучше всех,
# но наша позиция там больше всего объёма на лучшей цене. Из 1019 пар
# остаётся шесть. Спред меряется медианой по серии опросов, а не одним
# снимком: у HYPE подряд встречались 0.12 и 0.85, и по одному замеру он то
# проходил, то нет.
#   PEPE, ZEC — проверка гипотезы «волатильность без пропорциональной платы».
#         На шести инструментах убыток пассивной стратегии оказался равен
#         0.209 от собственной сигмы инструмента, связь почти идеальная
#         (r = 0.966). Сломать её мог бы только розничный поток: он менее
#         информирован, и наливают тебя не потому, что кто-то знает больше,
#         а потому что человек нажал кнопку.
#         Предсказание ДО сбора: PEPE -3.3 б.п. на сделку, ZEC -3.0. Лягут на
#         прямую — гипотеза мертва; выйдут заметно лучше — прямая ломается на
#         мем-коинах, и это уже находка.
SYMBOLS = ["BTC_USDT", "ETH_USDT", "SOL_USDT", "XAU_USDT", "HYPE_USDT",
           "XRP_USDT", "PEPE_USDT", "ZEC_USDT"]

# --- откуда -----------------------------------------------------------------

WS_URL = "wss://contract.mexc.com/edge"
REST_DEPTH = "https://contract.mexc.com/api/v1/contract/depth/{symbol}"
REST_TIME = "https://contract.mexc.com/api/v1/contract/ping"

# Сколько уровней просим в REST-снимке. Инкременты приходят по всей книге,
# снимок нужен как якорь для сборки и как эталон для проверки целостности.
# Потолок MEXC — 1500 уровней. Берём 1000: собранная книга достоверна только
# в ценовом диапазоне якоря, а на BTC 500 уровней — это всего ±50 USDT, цена
# выходит за них за минуты. С 1000 уровней и якорем раз в 2 минуты сверка
# сборки со снимком проходит на 93-100%.
SNAPSHOT_LEVELS = 1000

# --- ритм -------------------------------------------------------------------

PING_SECONDS = 15          # MEXC рвёт соединение примерно через минуту тишины
STATS_SECONDS = 60         # как часто писать строку статистики в лог
SNAPSHOT_SECONDS = 120     # принудительный снимок книги — якорь для проверки
CLOCK_SECONDS = 600        # редкая сверка часов через REST; основной замер
                           # идёт по ping/pong, он точнее (см. _record_clock)
RECONNECT_MAX_DELAY = 60   # потолок паузы между попытками переподключения

# --- диск -------------------------------------------------------------------

DATA_DIR = Path(__file__).resolve().parent / "data"
# Файл закрывается раз в ROTATE_MINUTES. Это не косметика: parquet получает
# подпись только при закрытии, и пока файл открыт, прочитать его нельзя. При
# часовой ротации свежий час данных был бы невидим для анализа — а отчёт на
# работающем диктофоне просто падал бы.
ROTATE_MINUTES = 10

# Уровень сжатия zstd. Замерено на живом потоке: 1 -> 308 МБ/сутки,
# 9 -> 276, 19 -> 244. Процессор на сервере всё равно простаивает, а разница
# в размере реальная, поэтому берём максимум. Информация не теряется.
COMPRESSION_LEVEL = 19

FLUSH_SECONDS = 10         # сброс буфера на диск не реже, чем раз в 10 секунд
FLUSH_ROWS = 2000          # ...или каждые 2000 событий (потолок паузы на сжатие)
RETENTION_DAYS = 14        # сырьё старше двух недель удаляем
MIN_FREE_GB = 3.0          # ниже этого порога запись останавливается


# --- переопределение из окружения -------------------------------------------
# Нужно, чтобы проверять инструменты, не правя файл: например прогнать сверку
# сборки за пару минут вместо получаса (OBR_SNAPSHOT_SECONDS=30).

SYMBOLS = [s.strip() for s in os.getenv("OBR_SYMBOLS", ",".join(SYMBOLS)).split(",") if s.strip()]
SNAPSHOT_SECONDS = int(os.getenv("OBR_SNAPSHOT_SECONDS", SNAPSHOT_SECONDS))
ROTATE_MINUTES = int(os.getenv("OBR_ROTATE_MINUTES", ROTATE_MINUTES))
RETENTION_DAYS = int(os.getenv("OBR_RETENTION_DAYS", RETENTION_DAYS))
COMPRESSION_LEVEL = int(os.getenv("OBR_ZSTD", COMPRESSION_LEVEL))
SNAPSHOT_LEVELS = int(os.getenv("OBR_SNAPSHOT_LEVELS", SNAPSHOT_LEVELS))
